-- =====================================================================
-- 5. BUSINESS_HOUR
-- 요일별 기본 영업시간 및 정기 휴무
-- DAY_OF_WEEK: 1=월 ... 7=일
-- =====================================================================

CREATE TABLE BUSINESS_HOUR (
    BUSINESS_HOUR_NO    NUMBER GENERATED BY DEFAULT AS IDENTITY,
    DAY_OF_WEEK         NUMBER(1)       NOT NULL,
    IS_OPEN             CHAR(1)         DEFAULT 'Y' NOT NULL,
    OPEN_TIME           VARCHAR2(5),
    CLOSE_TIME          VARCHAR2(5),
    CREATED_AT          TIMESTAMP        DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT          TIMESTAMP        DEFAULT SYSTIMESTAMP NOT NULL,

    CONSTRAINT BUSINESS_HOUR_PK
        PRIMARY KEY (BUSINESS_HOUR_NO),

    CONSTRAINT BUSINESS_HOUR_DAY_UK
        UNIQUE (DAY_OF_WEEK),

    CONSTRAINT BUSINESS_HOUR_DAY_CK
        CHECK (DAY_OF_WEEK BETWEEN 1 AND 7),

    CONSTRAINT BUSINESS_HOUR_OPEN_YN_CK
        CHECK (IS_OPEN IN ('Y', 'N')),

    CONSTRAINT BUSINESS_HOUR_OPEN_TIME_CK
        CHECK (
            OPEN_TIME IS NULL
            OR REGEXP_LIKE(OPEN_TIME, '^([01][0-9]|2[0-3]):[0-5][0-9]$')
        ),

    CONSTRAINT BUSINESS_HOUR_CLOSE_TIME_CK
        CHECK (
            CLOSE_TIME IS NULL
            OR REGEXP_LIKE(CLOSE_TIME, '^([01][0-9]|2[0-3]):[0-5][0-9]$')
        ),

    CONSTRAINT BUSINESS_HOUR_REQUIRED_TIME_CK
        CHECK (
            (IS_OPEN = 'Y' AND OPEN_TIME IS NOT NULL AND CLOSE_TIME IS NOT NULL)
            OR
            (IS_OPEN = 'N' AND OPEN_TIME IS NULL AND CLOSE_TIME IS NULL)
        )
);


