    PAYMENT_NO          NUMBER GENERATED BY DEFAULT AS IDENTITY,
    RESERVATION_NO      NUMBER          NOT NULL,
    MEMBER_NO           NUMBER,
    MEMBER_COUPON_NO    NUMBER,
    ORIGINAL_AMOUNT     NUMBER(12)      NOT NULL,
    DISCOUNT_AMOUNT     NUMBER(12)      DEFAULT 0 NOT NULL,
    PAYMENT_AMOUNT      NUMBER(12)      NOT NULL,
    PAYMENT_METHOD      VARCHAR2(20),
    PAYMENT_STATUS      VARCHAR2(20)    DEFAULT 'UNPAID' NOT NULL,
    PAID_AT             TIMESTAMP,
    REFUNDED_AT         TIMESTAMP,
    MEMO                VARCHAR2(500),
    REGDATE             TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATEDATE          TIMESTAMP,

    CONSTRAINT PAYMENT_PK
        PRIMARY KEY (PAYMENT_NO),

    CONSTRAINT PAYMENT_RESERVATION_FK
        FOREIGN KEY (RESERVATION_NO)
        REFERENCES RESERVATION(RESERVATION_NO),

    CONSTRAINT PAYMENT_MEMBER_FK
        FOREIGN KEY (MEMBER_NO)
        REFERENCES MEMBER(NO),

    CONSTRAINT PAYMENT_MEMBER_COUPON_FK
        FOREIGN KEY (MEMBER_COUPON_NO)
        REFERENCES MEMBER_COUPON(MEMBER_COUPON_NO),

    CONSTRAINT PAYMENT_RESERVATION_UK
        UNIQUE (RESERVATION_NO),

    CONSTRAINT PAYMENT_MEMBER_COUPON_UK
        UNIQUE (MEMBER_COUPON_NO),

    CONSTRAINT PAYMENT_ORIGINAL_AMOUNT_CK
        CHECK (ORIGINAL_AMOUNT >= 0),

    CONSTRAINT PAYMENT_DISCOUNT_AMOUNT_CK
        CHECK (
            DISCOUNT_AMOUNT >= 0
            AND DISCOUNT_AMOUNT <= ORIGINAL_AMOUNT
        ),

    CONSTRAINT PAYMENT_AMOUNT_CK
        CHECK (
            PAYMENT_AMOUNT >= 0
            AND PAYMENT_AMOUNT = ORIGINAL_AMOUNT - DISCOUNT_AMOUNT
        ),

    CONSTRAINT PAYMENT_METHOD_CK
        CHECK (
            PAYMENT_METHOD IS NULL
            OR PAYMENT_METHOD IN (
                'CARD',
                'CASH',
                'TRANSFER',
                'PREPAID'
            )
        ),

    CONSTRAINT PAYMENT_STATUS_CK
        CHECK (
            PAYMENT_STATUS IN (
                'UNPAID',
                'PAID',
                'REFUNDED'
            )
        )
);


