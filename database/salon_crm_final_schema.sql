-- =====================================================================
-- SECTION 8. 구현 시 반드시 지켜야 할 핵심 로직 메모
-- =====================================================================

-- [예약 가능 시간]
-- 실제 예약 가능 시간
--   = 영업시간
--   - SALON_HOLIDAY
--   - 기존 활성 예약
--   - 선택 시술의 소요시간
--
-- 기존 예약과 신규 예약의 겹침 판정:
--
-- existing.START_AT < requested.END_AT
-- AND existing.END_AT > requested.START_AT
-- AND existing.STATUS IN ('REQUESTED', 'CONFIRMED')
--
-- 실제 구현에서는 예약 생성 직전에 서버에서 다시 검사해야 합니다.
--
--
-- [동시 예약]
-- 단순히 화면에서 예약 가능 여부를 확인하는 것만으로는 부족합니다.
-- Service의 @Transactional과 DB Lock 또는 동시성 제어 전략을 사용하여
-- 같은 시간대의 동시 예약을 최종 차단해야 합니다.
--
--
-- [예약 완료 연결 흐름]
-- RESERVATION.STATUS = 'COMPLETED'
--      -> TREATMENT_HISTORY 생성
--      -> 고객 VISIT_COUNT / LAST_VISIT_DATE 갱신
--      -> PAYMENT 처리
--      -> 선택 구현 시 자재 STOCK_HISTORY 기록
--
--
-- [로그]
-- LOGIN_HISTORY는 로그인 성공/실패의 업무 데이터 기록용이며,
-- application/error/audit 로그 파일은 Logback으로 별도 저장합니다.
-- PASSWORD 등 민감정보는 절대 로그에 기록하지 않습니다.
--
--
-- [JPA]
-- RESERVATION.VERSION:
--      @Version
--
-- 상태값 컬럼:
--      @Enumerated(EnumType.STRING)
--
-- MEMBER / SERVICE_MENU / RESERVATION 등 IDENTITY PK:
--      @GeneratedValue(strategy = GenerationType.IDENTITY)
--
-- =====================================================================
-- 최종 통합 DDL 끝
-- =====================================================================
