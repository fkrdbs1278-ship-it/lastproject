-- =====================================================================
-- 1. MEMBER
-- 회원가입 / 로그인 / 마이페이지 / 권한 / 회원탈퇴
-- Spring Security의 사용자 계정 테이블
-- =====================================================================

CREATE TABLE MEMBER (
    NO                  NUMBER GENERATED BY DEFAULT AS IDENTITY,
    MEMBER_ID           VARCHAR2(100)  NOT NULL,
    PASSWORD            VARCHAR2(255)  NOT NULL,
    NAME                VARCHAR2(50)   NOT NULL,
    NICKNAME            VARCHAR2(50),
    EMAIL               VARCHAR2(100),
    PHONE               VARCHAR2(20)   NOT NULL,
    BIRTH_DATE          DATE,
    GENDER              VARCHAR2(10),
    ROLE                VARCHAR2(20)   DEFAULT 'USER' NOT NULL,
    STATUS              VARCHAR2(20)   DEFAULT 'ACTIVE' NOT NULL,
    AGREE_TERMS_YN      CHAR(1)        DEFAULT 'N' NOT NULL,
    AGREE_PRIVACY_YN    CHAR(1)        DEFAULT 'N' NOT NULL,
    LOGIN_FAIL_COUNT    NUMBER         DEFAULT 0 NOT NULL,
    LAST_LOGIN_DATE     TIMESTAMP,
    REGDATE             TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATE_DATE         TIMESTAMP,
    WITHDRAW_DATE       TIMESTAMP,

    CONSTRAINT MEMBER_PK
        PRIMARY KEY (NO),

    CONSTRAINT MEMBER_ID_UK
        UNIQUE (MEMBER_ID),

    CONSTRAINT MEMBER_EMAIL_UK
        UNIQUE (EMAIL),

    CONSTRAINT MEMBER_ROLE_CK
        CHECK (ROLE IN ('USER', 'ADMIN')),

    CONSTRAINT MEMBER_STATUS_CK
        CHECK (STATUS IN ('ACTIVE', 'BLOCKED', 'WITHDRAWN')),

    CONSTRAINT MEMBER_GENDER_CK
        CHECK (GENDER IN ('M', 'F') OR GENDER IS NULL),

    CONSTRAINT MEMBER_TERMS_CK
        CHECK (AGREE_TERMS_YN IN ('Y', 'N')),

    CONSTRAINT MEMBER_PRIVACY_CK
        CHECK (AGREE_PRIVACY_YN IN ('Y', 'N')),

    CONSTRAINT MEMBER_LOGIN_FAIL_CK
        CHECK (LOGIN_FAIL_COUNT >= 0)
);


