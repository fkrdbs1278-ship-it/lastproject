-- =====================================================================
-- 7. RESERVATION
-- 회원 / 비회원 / 전화 예약 통합
--
-- 회원 예약:
--   CUSTOMER_TYPE='MEMBER', MEMBER_NO 사용
--
-- 비회원/전화 고객:
--   CUSTOMER_TYPE='GUEST', GUEST_NAME/GUEST_PHONE 사용
--
-- 예약 당시 시술명과 소요시간을 SNAPSHOT으로 저장하여
-- 향후 SERVICE_MENU 변경 시에도 과거 예약 정보를 보존
--
-- VERSION:
--   JPA @Version 낙관적 락용
-- =====================================================================

CREATE TABLE RESERVATION (
    RESERVATION_NO              NUMBER GENERATED BY DEFAULT AS IDENTITY,
    MEMBER_NO                   NUMBER,
    SERVICE_MENU_NO             NUMBER          NOT NULL,
    CUSTOMER_TYPE               VARCHAR2(10)    NOT NULL,
    GUEST_NAME                  VARCHAR2(50),
    GUEST_PHONE                 VARCHAR2(20),
    RESERVATION_SOURCE          VARCHAR2(10)    DEFAULT 'ONLINE' NOT NULL,
    SERVICE_NAME_SNAPSHOT       VARCHAR2(100)   NOT NULL,
    DURATION_MINUTES_SNAPSHOT   NUMBER(4)       NOT NULL,
    START_AT                    TIMESTAMP       NOT NULL,
    END_AT                      TIMESTAMP       NOT NULL,
    REQUEST_MEMO                VARCHAR2(1000),
    STATUS                      VARCHAR2(20)    DEFAULT 'REQUESTED' NOT NULL,
    CANCEL_REASON               VARCHAR2(500),
    CANCELED_BY                 VARCHAR2(10),
    CONFIRMED_AT                TIMESTAMP,
    COMPLETED_AT                TIMESTAMP,
    CANCELED_AT                 TIMESTAMP,
    CREATED_AT                  TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    UPDATED_AT                  TIMESTAMP       DEFAULT SYSTIMESTAMP NOT NULL,
    VERSION                     NUMBER          DEFAULT 0 NOT NULL,

    CONSTRAINT RESERVATION_PK
        PRIMARY KEY (RESERVATION_NO),

    CONSTRAINT RESERVATION_MEMBER_FK
        FOREIGN KEY (MEMBER_NO)
        REFERENCES MEMBER(NO),

    CONSTRAINT RESERVATION_SERVICE_MENU_FK
        FOREIGN KEY (SERVICE_MENU_NO)
        REFERENCES SERVICE_MENU(NO),

    CONSTRAINT RESERVATION_CUSTOMER_TYPE_CK
        CHECK (CUSTOMER_TYPE IN ('MEMBER', 'GUEST')),

    CONSTRAINT RESERVATION_SOURCE_CK
        CHECK (RESERVATION_SOURCE IN ('ONLINE', 'PHONE')),

    CONSTRAINT RESERVATION_STATUS_CK
        CHECK (
            STATUS IN (
                'REQUESTED',
                'CONFIRMED',
                'COMPLETED',
                'CANCELED',
                'NO_SHOW'
            )
        ),

    CONSTRAINT RESERVATION_CANCELED_BY_CK
        CHECK (
            CANCELED_BY IS NULL
            OR CANCELED_BY IN ('USER', 'ADMIN')
        ),

    CONSTRAINT RESERVATION_DURATION_CK
        CHECK (DURATION_MINUTES_SNAPSHOT > 0),

    CONSTRAINT RESERVATION_PERIOD_CK
        CHECK (END_AT > START_AT),

    CONSTRAINT RESERVATION_CUSTOMER_CK
        CHECK (
            (CUSTOMER_TYPE = 'MEMBER' AND MEMBER_NO IS NOT NULL)
            OR
            (
                CUSTOMER_TYPE = 'GUEST'
                AND MEMBER_NO IS NULL
                AND GUEST_NAME IS NOT NULL
                AND GUEST_PHONE IS NOT NULL
            )
        )
);


