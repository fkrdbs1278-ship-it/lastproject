package com.young04.lastproject.customerprofile.dto;

import lombok.Getter;
import lombok.Setter;


/**
 * =========================================================
 * 관리자 고객 CRM 검색 조건
 * =========================================================
 *
 * 고객관리 목록:
 *
 * /admin/customers
 *
 * 에서 사용하는 검색 조건입니다.
 *
 *
 * 지원 검색:
 *
 * 1. 고객 이름 / 전화번호
 * 2. 회원 / 비회원
 * 3. 고객 등급
 * 4. 활성 / 비활성
 * 5. 장기 미방문 고객
 *
 *
 * 재방문 관리는 별도의 "재방문 권장일"을
 * 사용하지 않습니다.
 *
 * LAST_VISIT_DATE를 기준으로
 * 30일 / 60일 이상 미방문 고객을 조회합니다.
 */
@Getter
@Setter
public class CustomerSearchCondition {


    // =====================================================
    // 이름 / 전화번호 통합 검색
    // =====================================================

    /**
     * 고객 이름 또는 전화번호 검색
     *
     * 예:
     *
     * 홍길동
     * 01012345678
     */
    private String keyword;



    // =====================================================
    // 회원 유형
    // =====================================================

    /**
     * MEMBER = 회원 고객
     * GUEST  = 비회원 / 전화예약 고객
     *
     * null 또는 빈 문자열 = 전체
     */
    private String customerType;



    // =====================================================
    // 고객 등급
    // =====================================================

    /**
     * NORMAL
     * REGULAR
     * VIP
     *
     * null 또는 빈 문자열 = 전체
     */
    private String gradeCode;



    // =====================================================
    // 활성 여부
    // =====================================================

    /**
     * Y = 활성 고객
     * N = 비활성 고객
     *
     * null 또는 빈 문자열 = 전체
     */
    private String activeYn;



    // =====================================================
    // 장기 미방문
    // =====================================================

    /**
     * 최근 방문일 기준
     * 장기 미방문 고객 조회
     *
     * 30 = 30일 이상 미방문
     * 60 = 60일 이상 미방문
     *
     * null = 전체
     *
     *
     * 예:
     *
     * 오늘이 2026-08-31이고
     * inactiveDays = 30이면
     *
     * LAST_VISIT_DATE <= 2026-08-01
     *
     * 인 고객을 조회합니다.
     */
    private Integer inactiveDays;
}